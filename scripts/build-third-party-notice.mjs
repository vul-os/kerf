#!/usr/bin/env node
// build-third-party-notice.mjs — regenerate THIRD-PARTY-LICENSES.md from the installed tree.
//
// WHY THIS EXISTS
// ---------------
// Kerf's own source is MIT, and after the src/cloud carve-out was removed the LICENSE file is
// byte-identical to canonical MIT. But the shipped application links several libraries that are
// NOT MIT — most importantly the geometry kernels:
//
//   opencascade.js           LGPL-2.1-only     the B-rep kernel
//   occt-import-js           LGPL-2.1          STEP/IGES import
//   @salusoft89/planegcs     LGPL-2.0-or-later the sketch constraint solver
//   web-ifc                  MPL-2.0           IFC read/write
//
// That combination is fine — LGPL and MPL both permit use from MIT-licensed code, which is
// precisely why this project chose them over GPL alternatives (see the kiutils decision: GPLv3
// was rejected to stay MIT-clean, LGPL was not). But "MIT" on its own describes Kerf's code, not
// the whole distribution, and saying so plainly is both more accurate and more useful to anyone
// redistributing a build.
//
// Generated rather than hand-maintained so it cannot drift from package.json.
//
//   node scripts/build-third-party-notice.mjs

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))

function licenceOf(name) {
  const f = join(ROOT, 'node_modules', name, 'package.json')
  if (!existsSync(f)) return null
  try {
    const j = JSON.parse(readFileSync(f, 'utf8'))
    let l = typeof j.license === 'string'
      ? j.license
      : (j.license && j.license.type) || (Array.isArray(j.licenses) && j.licenses[0]?.type)
    // Some packages ship a LICENSE file without declaring `license` in package.json
    // (@tscircuit/core is MIT this way). Read the file rather than report UNDECLARED.
    if (!l) {
      for (const f of ['LICENSE', 'LICENSE.md', 'LICENSE.txt']) {
        const lf = join(ROOT, 'node_modules', name, f)
        if (!existsSync(lf)) continue
        const head = readFileSync(lf, 'utf8').slice(0, 200)
        const m = head.match(/(MIT|Apache License|BSD|ISC|Mozilla Public License)/i)
        if (m) { l = m[1].toLowerCase().startsWith('apache') ? 'Apache-2.0 (from LICENSE file)'
               : m[1].toLowerCase().startsWith('mozilla') ? 'MPL-2.0 (from LICENSE file)'
               : `${m[1].toUpperCase()} (from LICENSE file)`; break }
      }
    }
    return { licence: l || 'UNDECLARED', version: j.version, homepage: j.homepage || j.repository?.url }
  } catch { return null }
}

const deps = Object.keys(pkg.dependencies || {}).sort()
const rows = deps.map((n) => ({ name: n, ...(licenceOf(n) || { licence: 'NOT INSTALLED' }) }))

// Anything that is not a plain permissive licence gets called out by name above the table,
// because those are the ones with redistribution obligations someone actually has to read.
const NOTABLE = /GPL|MPL|EPL|CDDL|CC-BY|UNDECLARED|NOT INSTALLED/i
const notable = rows.filter((r) => NOTABLE.test(r.licence))
const permissive = rows.filter((r) => !NOTABLE.test(r.licence))

const byLicence = new Map()
for (const r of permissive) {
  if (!byLicence.has(r.licence)) byLicence.set(r.licence, [])
  byLicence.get(r.licence).push(r.name)
}

const out = `# Third-party licences

Kerf's own source code is **MIT** — see [LICENSE](./LICENSE), which is byte-identical to the
canonical MIT text with no carve-outs or excluded paths.

The application it builds, however, links libraries under other licences. This file lists them.
It is generated by \`scripts/build-third-party-notice.mjs\` from the installed dependency tree, so
it does not drift from \`package.json\`.

## Libraries with redistribution obligations

These are the ones to read before redistributing a build. All of them permit use from
MIT-licensed code — that is why they were chosen over GPL alternatives — but several require
that you can relink or replace the library, and that you pass their licence text along.

| Package | Licence | What it does |
|---|---|---|
${notable.map((r) => {
  const role = {
    'opencascade.js': 'B-rep geometry kernel',
    'occt-import-js': 'STEP / IGES import',
    '@salusoft89/planegcs': '2D sketch constraint solver',
    'web-ifc': 'IFC4 read / write',
  }[r.name] || ''
  return `| \`${r.name}\` | ${r.licence} | ${role} |`
}).join('\n')}

**LGPL (opencascade.js, occt-import-js, planegcs).** Kerf calls these as libraries and does not
modify them. If you redistribute a Kerf build you must keep their licence notices and allow a
recipient to substitute their own build of the library.

**MPL-2.0 (web-ifc).** File-level copyleft: modifications to *its* files stay MPL, but combining
it with MIT code does not affect Kerf's licence.

## Permissive dependencies

${[...byLicence.entries()].sort((a, b) => b[1].length - a[1].length)
  .map(([lic, names]) => `**${lic}** (${names.length}) — ${names.map((n) => `\`${n}\``).join(', ')}`)
  .join('\n\n')}

---

Runtime dependencies only; build-time \`devDependencies\` are not redistributed and are not listed.
Regenerate with \`node scripts/build-third-party-notice.mjs\`.
`

writeFileSync(join(ROOT, 'THIRD-PARTY-LICENSES.md'), out)
console.log(`third-party notice: ${rows.length} runtime deps, ${notable.length} with obligations`)
