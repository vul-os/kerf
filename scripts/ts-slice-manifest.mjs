#!/usr/bin/env node
// ts-slice-manifest.mjs — generate the ownership manifest for T-513…T-517.
//
// WHY THIS EXISTS
// ---------------
// `src/components/` has ~299 files in one flat directory. The other G1 slices are
// directory-scoped and therefore unambiguous — an agent owns every file in its folders. This one
// is not: five slices split a single directory by *role*, so without an explicit per-file
// assignment two agents can silently claim the same file, and the migration invariant ("one agent
// owns a file") is only as good as the list.
//
// `docs/typescript-migration.md` requires this manifest to exist before T-513…T-517 run
// concurrently. This script is the generator; its output is pasted into that document, which
// remains the authoritative surface.
//
// Classification is by filename role, deliberately mechanical so it is reproducible and arguable
// from the outside rather than being one agent's judgement call. Every file lands in exactly one
// slice — the script asserts that — and the tail slice absorbs anything unmatched, so nothing can
// be silently dropped.

import { readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

const DIR = 'src/components'

// Role-based slices, evaluated in order; first match wins. Anything unmatched falls to T-517,
// which is why T-517 has no matcher of its own — it is the remainder by construction.
const SLICES = [
  {
    id: 'T-513',
    title: 'viewports & renderers',
    match: (n) =>
      /^(Renderer|FeatureRenderer|SketchView|PCBView|CfdViewport|TopoView|QuadMeshView|BIMView|OrbitViewer|AttitudeViewer|FEMDeformedShape|RenderView|SchematicView|SectionView|LayoutViewer|ThermalNetworkViewer|NestingLayoutView|PrintSliceView|MEPView|RailingView|StairView|WiringView|LadderView|PLCView|RFView|CAMView|FEMView|DrawingView|SimulationView|ToleranceView|FeatureView)/.test(n) ||
      /^(CurvatureCombOverlay|Gumball|LightGizmos|Pmi3DOverlay|LadderPowerFlowOverlay|DerivedCacheOverlay|CloudLayer|RatsnestLayer)/.test(n),
  },
  {
    id: 'T-514',
    title: 'editors',
    match: (n) => /Editor|Canvas$|Canvas\./.test(n),
  },
  {
    id: 'T-515',
    title: 'domain panels A–L',
    match: (n) => /Panel/.test(n) && /^[A-L]/.test(n),
  },
  {
    id: 'T-516',
    title: 'domain panels M–Z + tables/pickers',
    match: (n) => /Panel|Picker|Table|Chart|Toolbar/.test(n),
  },
  {
    id: 'T-517',
    title: 'chrome, primitives & remainder',
    match: () => true,
  },
]

const all = readdirSync(DIR)
  .filter((f) => /\.(jsx?|tsx?)$/.test(f))
  .filter((f) => statSync(join(DIR, f)).isFile())
  .sort()

const pending = all.filter((f) => /\.jsx?$/.test(f))

const assigned = new Map(SLICES.map((s) => [s.id, []]))
for (const f of pending) {
  const slice = SLICES.find((s) => s.match(f))
  assigned.get(slice.id).push(f)
}

// Invariant: every pending file is assigned exactly once. If this ever fails the manifest is
// unsafe to run concurrently, so fail loudly rather than emitting a subtly wrong list.
const total = [...assigned.values()].reduce((n, v) => n + v.length, 0)
if (total !== pending.length) {
  console.error(`ts-slice-manifest: FAIL — ${pending.length} pending files but ${total} assigned.`)
  process.exit(1)
}

console.log(`# T-513…T-517 slice manifest — ${DIR}`)
console.log(`# Generated by scripts/ts-slice-manifest.mjs. ${all.length} files total, ${pending.length} still .js/.jsx.`)
console.log(`# One agent owns a file. If two slices below list the same name, the manifest is wrong — fix it before running.`)
console.log()
for (const s of SLICES) {
  const files = assigned.get(s.id)
  console.log(`## ${s.id} — ${s.title} (${files.length} files)`)
  console.log()
  for (const f of files) console.log(`- ${f}`)
  console.log()
}
